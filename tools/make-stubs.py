#!/usr/bin/env python3
"""make-stubs.py — generate aarch64 stub libraries for the firmware's SDL3.

The device supplies libSDL3 at runtime; Zig's sysroot does not, so linking needs
something to resolve against. This tool writes a stub shared object whose SONAME
matches SDL3's, containing exactly the symbols the port references.

Symbols are read from the build's object files, so the stub can never drift from
what the code actually calls.

Usage:
  tools/make-stubs.py --objects build-arm64 --lib build-arm64/stubs/lib \
                      --include build-arm64/stubs/include --zig deps/zig/zig
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

# Each stub advertises the real SONAME, so at runtime the loader binds the
# firmware's own SDL3/GLES/EGL instead of our stub.
STUBS = [
    # (soname, link name, symbol predicate)
    ("libSDL3.so.0", "libSDL3.so", lambda n: n.startswith("SDL_")),
    ("libGLESv2.so.2", "libGLESv2.so", lambda n: re.match(r"^gl[A-Z]", n) is not None),
    ("libEGL.so.1", "libEGL.so", lambda n: re.match(r"^egl[A-Z]", n) is not None),
]

ALL_RE = re.compile(r"^(SDL_|gl[A-Z]|egl[A-Z])[A-Za-z0-9_]*$")


def undefined_symbols(object_dirs: list[Path]) -> list[str]:
    syms: set[str] = set()
    for root in object_dirs:
        for obj in root.rglob("*.o"):
            try:
                out = subprocess.run(["nm", "-u", str(obj)], capture_output=True, text=True).stdout
            except FileNotFoundError:
                sys.exit("nm not found (binutils)")
            for line in out.splitlines():
                parts = line.split()
                if not parts:
                    continue
                name = parts[-1]
                if ALL_RE.match(name):
                    syms.add(name)
    return sorted(syms)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--objects", type=Path, required=True, help="build dir to scan for .o files")
    ap.add_argument("--lib", type=Path, required=True, help="output directory for stub libraries")
    ap.add_argument("--include", type=Path, required=True, help="output directory for stub headers")
    ap.add_argument("--zig", type=Path, required=True)
    ap.add_argument("--target", default="aarch64-linux-gnu.2.28")
    args = ap.parse_args()

    syms = undefined_symbols([args.objects])
    print(f"make-stubs: {len(syms)} firmware symbols referenced")
    if not syms:
        print("make-stubs: nothing to stub (already linked?)")
        return 0

    args.lib.mkdir(parents=True, exist_ok=True)
    args.include.mkdir(parents=True, exist_ok=True)

    written = 0
    for soname, link_name, pred in STUBS:
        subset = [x for x in syms if pred(x)]
        if not subset:
            continue
        src = args.lib / (soname.replace(".", "_") + "_stub.c")
        body = [
            f"// generated by tools/make-stubs.py — link-time stubs for {soname}",
            "typedef int pd_stub_t;",
        ]
        for s in subset:
            body.append(f"pd_stub_t {s}(void) {{ return 0; }}")
        src.write_text("\n".join(body) + "\n")

        out = args.lib / soname
        cmd = [
            str(args.zig), "cc", "-target", args.target, "-shared", "-fPIC",
            "-Wl,-soname," + soname, str(src), "-o", str(out),
        ]
        print(f"make-stubs: {soname}: {len(subset)} symbols")
        subprocess.run(cmd, check=True)
        for link in (link_name, soname):
            lp = args.lib / link
            if not lp.exists():
                lp.symlink_to(soname)
        written += 1
        print(f"make-stubs: wrote {out} ({out.stat().st_size} bytes)")

    if not written:
        print("make-stubs: no stub libraries produced")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
